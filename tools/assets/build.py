#!/usr/bin/env python3
"""rally-web original-asset build: original_version/archives/*.rff -> public/assets/ (docs/ASSETS.md).

  npm run assets -- [options]            (= python3 -I tools/assets/build.py [options], .venv python if present)

  --stages all|id,id     stage phase: run every part's build_stage for these stages (ids as in PORTED_ORDER,
                         e.g. corsica-1-f,hillclimb-1a-f)
  --cars all|Name,Name   car phase: run every part's build_cars once with these car names (Cars.rff cars/<Name>)
  --audio                global phase: run every part's build_global (the audio bank and other shared data)
                         (no phase option at all = all three phases, everything)
  --parts p,p            restrict to these part plugins (tools/assets/parts/<p>.py; '_name' parts only when named)
  --jobs N               parallel stage workers (default: CPU count, max 16)
  --out DIR              output root (default public/assets)
  --clean                remove the selected parts' existing outputs for the selected stages/cars/global first
                         (never touches other parts or the shared tex/ folder; rm -rf public/assets for a full reset)
  --no-extract           do not (re)extract the archive cache before building
  --list                 list parts, stages and cars, then exit
  --selftest             check the archive layer, the engine lookup rules and the .rtex conversion against the
                         verified research tools (when research/ exists), then exit
The manifest (public/assets/manifest.json) is regenerated by scanning --out at the end of every run.
Exit status 1 when any part failed.
"""
import argparse
import os
import sys
import time
import traceback

HERE = os.path.dirname(os.path.abspath(__file__))
LIB = os.path.join(HERE, 'lib')
sys.path[0:0] = [LIB, os.path.join(LIB, 'formats')]

try:
    import numpy  # noqa: F401,E402
except ImportError:
    sys.exit('tools/assets needs numpy + Pillow: uv venv .venv && uv pip install -r tools/assets/requirements.txt '
             '(then npm run assets uses .venv/bin/python; docs/ASSETS.md)')
import archive as A  # noqa: E402
import context as C  # noqa: E402
import manifest as M  # noqa: E402
import plugins as P  # noqa: E402
import stages as S  # noqa: E402
import textures as T  # noqa: E402
import vfs as V  # noqa: E402

DEFAULT_OUT = os.path.join(A.REPO, 'public', 'assets')


def log(msg):
    print(msg, flush=True)


def car_names(vfs):
    """Original spelling of every car folder (cars/<Name>/Geom.con) in Cars.rff."""
    out = set()
    for v, hits in vfs.index.items():
        p = v.split('/')
        if len(p) == 3 and p[0] == 'cars' and p[2] == 'geom.con':
            out.add(hits[0][1].replace('\\', '/').split('/')[1])
    return sorted(out)


def pick(arg, available, what, key=lambda s: s):
    if arg in (None, ''):
        return []
    if arg == 'all':
        return list(available)
    want = [x.strip() for x in arg.split(',') if x.strip()]
    lut = {key(a): a for a in available}
    bad = [w for w in want if key(w) not in lut]
    if bad:
        raise SystemExit('unknown %s: %s' % (what, ', '.join(bad)))
    return [lut[key(w)] for w in want]


# ------------------------------------------------------------------------------------------ workers
_G = {}         # set in the parent before forking: vfs, parts, out


def _registry():
    reg = _G.get('registry')
    if reg is None or _G.get('registry_pid') != os.getpid():
        reg = _G['registry'] = T.TextureRegistry(_G['vfs'], _G['out'], log)
        _G['registry_pid'] = os.getpid()
    return reg


def _run(fn, ctx, *args):
    t0 = time.time()
    try:
        fn(ctx, *args)
        return {'ok': True, 'seconds': round(time.time() - t0, 2), 'warnings': len(ctx.warnings)}
    except Exception:  # noqa
        err = traceback.format_exc()
        log('[%s %s] FAILED\n%s' % (ctx.part, ctx.stage.id if ctx.stage else '-', err))
        return {'ok': False, 'seconds': round(time.time() - t0, 2), 'warnings': len(ctx.warnings), 'error': err}


def _stage_job(sid):
    vfs, out = _G['vfs'], _G['out']
    reg = _registry()
    w0, r0 = reg.written, reg.reused
    st = S.load_stage(sid, vfs)
    res = []
    for name, mod in _G['parts'].items():
        fn = getattr(mod, 'build_stage', None)
        if not callable(fn):
            continue
        o = C.Output(os.path.join(out, 'stages', sid), name)
        if _G['clean']:
            o.clean()
        ctx = C.BuildContext(name, out, vfs, reg, A.FULL, stage=st, out=o, log=log)
        res.append(dict(_run(fn, ctx, st), stage=sid, part=name))
    missing = sorted('%s' % n for n, s in reg.missing if s == sid)
    return res, reg.written - w0, reg.reused - r0, missing


# ------------------------------------------------------------------------------------------ main
def main(argv):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0],
                                 formatter_class=argparse.RawDescriptionHelpFormatter, epilog=__doc__)
    ap.add_argument('--stages')
    ap.add_argument('--cars')
    ap.add_argument('--audio', action='store_true')
    ap.add_argument('--parts')
    ap.add_argument('--jobs', type=int, default=min(16, os.cpu_count() or 1))
    ap.add_argument('--out', default=DEFAULT_OUT)
    ap.add_argument('--clean', action='store_true')
    ap.add_argument('--no-extract', action='store_true')
    ap.add_argument('--list', action='store_true')
    ap.add_argument('--selftest', action='store_true')
    a = ap.parse_args(argv)

    if a.selftest:
        import selftest
        return selftest.main()
    if not A.have_originals():
        log('no original archives under %s/archives -- nothing to build (the game falls back to its procedural '
            'visuals without public/assets)' % os.path.relpath(A.ORIGINAL, A.REPO))
        return 1
    out = os.path.abspath(a.out)
    t0 = time.time()
    vfs = V.Vfs()
    all_stages = S.ported_order()
    all_cars = car_names(vfs)
    wanted_parts = [p.strip() for p in a.parts.split(',') if p.strip()] if a.parts else None
    parts = P.discover(wanted=wanted_parts)

    if a.list:
        log('parts (%s):' % P.PARTS_DIR)
        for n, m in parts.items():
            log('  %-14s %s' % (n, ', '.join(h for h in P.HOOKS if callable(getattr(m, h, None)))))
        log('stages: ' + ' '.join(all_stages))
        log('cars:   ' + ' '.join(all_cars))
        return 0

    every = a.stages is None and a.cars is None and not a.audio
    stages = pick('all' if every else a.stages, all_stages, 'stage id(s)')
    cars = pick('all' if every else a.cars, all_cars, 'car name(s)', key=str.lower)
    do_global = every or a.audio
    if not parts:
        log('no part plugins selected (tools/assets/parts/*.py) -- only the manifest is rewritten')

    if not a.no_extract:
        A.ensure_extracted(jobs=a.jobs, log=log)

    _G.update(vfs=vfs, parts=parts, out=out, clean=a.clean)
    results = []
    tex_written = tex_reused = 0
    missing = {}

    # ---- stage phase
    stage_parts = [n for n, m in parts.items() if callable(getattr(m, 'build_stage', None))]
    if stages and stage_parts:
        log('stage phase: %d stage(s) x %s, %d job(s)' % (len(stages), ','.join(stage_parts), a.jobs))
        jobs = max(1, min(a.jobs, len(stages)))
        if jobs == 1:
            outs = [_stage_job(s) for s in stages]
        else:
            import multiprocessing as mp
            ctx = mp.get_context('fork') if hasattr(os, 'fork') else mp.get_context()
            with ctx.Pool(jobs) as pool:
                outs = list(pool.imap_unordered(_stage_job, stages))
        for res, w, r, miss in outs:
            results += res
            tex_written += w
            tex_reused += r
            if miss and res:
                missing[res[0]['stage']] = miss

    # ---- car phase (the parent's registry; the stage phase may have used it too when it ran in-process)
    reg = _registry()
    w0, r0 = reg.written, reg.reused
    car_parts = [n for n, m in parts.items() if callable(getattr(m, 'build_cars', None))]
    if cars and car_parts:
        log('car phase: %d car(s) x %s' % (len(cars), ','.join(car_parts)))
        for n in car_parts:
            ctx = C.BuildContext(n, out, vfs, reg, A.FULL, log=log)
            if a.clean:
                for c in cars:
                    ctx.car_out(c).clean()
            results.append(dict(_run(parts[n].build_cars, ctx, cars), stage='cars', part=n))

    # ---- global phase
    glob_parts = [n for n, m in parts.items() if callable(getattr(m, 'build_global', None))]
    if do_global and glob_parts:
        log('global phase: %s' % ','.join(glob_parts))
        for n in glob_parts:
            o = C.Output(os.path.join(out, 'global'), n)
            if a.clean:
                o.clean()
            ctx = C.BuildContext(n, out, vfs, reg, A.FULL, out=o, log=log)
            results.append(dict(_run(parts[n].build_global, ctx), stage='global', part=n))
    tex_written += reg.written - w0
    tex_reused += reg.reused - r0

    # ---- manifest (scan, never merge)
    os.makedirs(out, exist_ok=True)
    m = M.write(out)
    bad = [r for r in results if not r['ok']]
    log('')
    log('%d part run(s): %d ok, %d failed; textures written %d, reused %d; %.1f s'
        % (len(results), len(results) - len(bad), len(bad), tex_written, tex_reused, time.time() - t0))
    for sid, miss in sorted(missing.items()):
        log('  %s: %d texture name(s) did not resolve: %s%s' % (sid, len(miss), ', '.join(miss[:6]),
                                                              ' ...' if len(miss) > 6 else ''))
    for r in bad:
        log('  FAILED %s %s: %s' % (r['part'], r['stage'], r['error'].strip().splitlines()[-1]))
    log('manifest: %d stage(s), %d car(s), global %s, %d texture(s) -> %s'
        % (len(m['stages']), len(m['cars']), m['global'] or '[]', m['textures'],
           os.path.relpath(os.path.join(out, 'manifest.json'), A.REPO)))
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
