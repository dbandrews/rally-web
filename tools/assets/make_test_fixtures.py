#!/usr/bin/env python3
"""Regenerate tests/assets/fixtures/*.json (tiny, committed) from the verified numpy decoders.

  .venv/bin/python -I tools/assets/make_test_fixtures.py

dxt.json   S3TC blocks + the RGBA8 that fmt_textures.decode_dxt (bit-exact with SwiftShader's S3TC decode,
           research/formats/textures.md §8) produces: deterministic synthetic blocks covering both DXT1
           colour modes and both DXT5 alpha modes, sub-4 levels (2x2, 1x8, 8x1), and real blocks cut from
           shipped textures (punch-through DXT1 foliage, DXT3 / DXT5 billboards).
rtex.json  two real pipeline outputs (.rtex bytes) with the expected RGBA of every level: an 8x8 DXT1
           (2 levels) and a 16x16 P8 lightmap expanded through its Track.pal (5 levels).
Needs original_version/ (the real blocks); fails loudly without it.
"""
import base64
import json
import os
import random
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path[0:0] = [os.path.join(HERE, 'lib'), os.path.join(HERE, 'lib', 'formats')]

import numpy as np  # noqa: E402

import archive as A  # noqa: E402
import fmt_textures as FT  # noqa: E402
import rtex as R  # noqa: E402
import textures as T  # noqa: E402
import vfs as V  # noqa: E402

OUT = os.path.join(A.REPO, 'tests', 'assets', 'fixtures')
FOURCC = {'DXT1': 12, 'DXT3': 14, 'DXT5': 16}
b64 = lambda b: base64.b64encode(bytes(b)).decode('ascii')  # noqa: E731


def synthetic(fmt, rnd, n):
    bs = 8 if fmt == 'DXT1' else 16
    blocks = bytearray()
    for i in range(n):
        blk = bytearray(rnd.getrandbits(8) for _ in range(bs))
        co = 0 if fmt == 'DXT1' else 8
        c0 = blk[co] | blk[co + 1] << 8
        c1 = blk[co + 2] | blk[co + 3] << 8
        if (i % 2 == 0) != (c0 > c1):           # alternate 4-colour / 3-colour colour blocks
            blk[co:co + 2], blk[co + 2:co + 4] = blk[co + 2:co + 4], blk[co:co + 2]
        if i % 5 == 0:
            blk[co:co + 4] = blk[co:co + 2] * 2  # c0 == c1 (3-colour mode in DXT1)
        if fmt == 'DXT5' and (i % 3 == 0) != (blk[0] > blk[1]):
            blk[0], blk[1] = blk[1], blk[0]      # alternate 8-alpha / 6-alpha
        blocks += blk
    return bytes(blocks)


def case(name, fmt, data, w, h):
    img, _ = FT.decode_dxt(data, FOURCC[fmt], w, h)
    return {'name': name, 'format': fmt, 'width': w, 'height': h, 'data': b64(data), 'rgba': b64(img.tobytes())}


def real_blocks(vfs, base, arch, nblocks, fmt_want):
    hits = [(a, m) for v, hs in vfs.index.items() if v.rsplit('/', 1)[-1] == base.lower() for a, m in hs if a == arch]
    a, m = hits[0]
    b = vfs.archives.read(a, m)
    hd = FT.dds_layout(b)
    assert FT.FMT_NAMES[hd['fmt']] == fmt_want, (base, hd['fmt'])
    w = hd['w']
    bs = 8 if fmt_want == 'DXT1' else 16
    bw = max(1, (w + 3) // 4)
    # the first two block rows, nblocks // 2 blocks each (a 4*nblocks/2 x 8 crop)
    half = nblocks // 2
    rows = [b[128 + r * bw * bs: 128 + r * bw * bs + half * bs] for r in range(2)]
    return b''.join(rows), half * 4, 8


def main():
    vfs = V.Vfs()
    rnd = random.Random(20021029)
    cases = []
    for fmt in ('DXT1', 'DXT3', 'DXT5'):
        bs = 8 if fmt == 'DXT1' else 16
        cases.append(case('synthetic 16x16 ' + fmt, fmt, synthetic(fmt, rnd, 16), 16, 16))
        cases.append(case('synthetic 2x2 ' + fmt, fmt, synthetic(fmt, rnd, 1), 2, 2))
        cases.append(case('synthetic 1x8 ' + fmt, fmt, synthetic(fmt, rnd, 2), 1, 8))
        cases.append(case('synthetic 8x1 ' + fmt, fmt, synthetic(fmt, rnd, 2), 8, 1))
        assert len(synthetic(fmt, random.Random(1), 1)) == bs
    for base, arch, fmt in (('co_grennleaf_01_se.dds', 'Misc', 'DXT1'), ('nzbushD.dds', 'corsica1r', 'DXT5'),
                            ('SKYTOP_A.dds', 'rallycross3r', 'DXT3'), ('HCPine1.dds', 'hillclimb1af', 'DXT3')):
        data, w, h = real_blocks(vfs, base, arch, 8, fmt)
        cases.append(case('%s:%s 16x8' % (arch, base), fmt, data, w, h))
    punch = [c for c in cases if c['name'].startswith('Misc:co_grennleaf')][0]
    assert np.any(np.frombuffer(base64.b64decode(punch['rgba']), np.uint8)[3::4] == 0), 'no punch-through texel'

    rtexs = []
    reg = T.TextureRegistry(vfs, os.path.join(A.CACHE_ROOT, 'tmp', 'fixtures'))
    for base, arch in (('HC_PlasticStripe_01_FU.dds', 'Misc'), ('Track100.tga', 'hillclimb1br')):
        hits = [(a, m) for v, hs in vfs.index.items() if v.rsplit('/', 1)[-1] == base.lower() for a, m in hs if a == arch]
        tid = reg.use_file(*hits[0])
        blob = open(os.path.join(reg.dir, tid + '.rtex'), 'rb').read()
        u = R.unpack(blob)
        rtexs.append({'name': '%s:%s' % (arch, base), 'texId': tid, 'rtex': b64(blob), 'format': u['formatName'],
                      'levels': [b64(T.decode_level_rgba(u, i).tobytes()) for i in range(len(u['levels']))]})
    os.makedirs(OUT, exist_ok=True)
    head = 'generated by tools/assets/make_test_fixtures.py from the verified numpy decoder (do not edit)'
    with open(os.path.join(OUT, 'dxt.json'), 'w') as f:
        json.dump({'note': head, 'cases': cases}, f, indent=0)
    with open(os.path.join(OUT, 'rtex.json'), 'w') as f:
        json.dump({'note': head, 'files': rtexs}, f, indent=0)
    for fn in ('dxt.json', 'rtex.json'):
        print('wrote', os.path.relpath(os.path.join(OUT, fn), A.REPO), os.path.getsize(os.path.join(OUT, fn)), 'bytes')


if __name__ == '__main__':
    main()
