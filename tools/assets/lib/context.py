"""What a part plugin gets: BuildContext (`ctx`) and its Output writer.

Output layout under the output root (default public/assets/):

  stages/<stage id>/<part>.json   (+ <part>.<ext>, <part>/<...>)    build_stage(ctx, stage)
  cars/<CarName>/<part>.json      (+ <part>.<ext>, <part>/<...>)    build_cars(ctx, cars)
  global/<part>.json              (+ <part>.<ext>, <part>/<...>)    build_global(ctx)
  tex/<texId>.rtex                ctx.textures (shared, content-addressed)
  manifest.json                   regenerated by scanning after every run

A part's output for a stage/car/global slot is PRESENT iff its `<part>.json` exists. Write binaries first
and the json LAST (Output does every write atomically), so a reader never sees a json whose files are
missing. Names are restricted to `<part>.<ext>` and `<part>/<relative path>` so parts can never clobber
each other.
"""
import json
import os
import re
import shutil

import textures as T

_NAME_RE = re.compile(r'^[A-Za-z0-9_][A-Za-z0-9_.\-]*$')


class Output:
    """Atomic writer bound to one folder and one part name."""

    def __init__(self, folder, part):
        self.folder = folder
        self.part = part
        self.json_name = part + '.json'

    def path(self, name):
        """Absolute path for `name` = '<part>.<ext>' or '<part>/<rel>' (validated)."""
        n = name.replace('\\', '/')
        ok = n.startswith(self.part + '.') or n.startswith(self.part + '/')
        segs = n.split('/')
        if not ok or any(s in ('', '.', '..') or not _NAME_RE.match(s) for s in segs):
            raise ValueError("part %r may only write '%s.<ext>' or '%s/<path>', not %r"
                             % (self.part, self.part, self.part, name))
        return os.path.join(self.folder, *segs)

    def write_bytes(self, name, data):
        p = self.path(name)
        T.atomic_write(p, bytes(data))
        return p

    def write_text(self, name, text):
        return self.write_bytes(name, text.encode('utf-8'))

    def write_json(self, name, obj, indent=None):
        txt = json.dumps(obj, indent=indent, separators=None if indent else (',', ':'), allow_nan=False)
        return self.write_text(name, txt)

    def commit(self, obj, indent=None):
        """Write `<part>.json` (call LAST: it marks the part as present)."""
        return self.write_json(self.json_name, obj, indent)

    def clean(self):
        """Remove this part's files in this folder (`<part>.*` and `<part>/`). In-flight temp files of a
        concurrent run (`*.tmp.<pid>.<rand>`, textures.atomic_write) are left alone: deleting one made that
        run's os.replace fail. Do not --clean a part while another run builds the SAME part and slot."""
        if not os.path.isdir(self.folder):
            return
        for f in os.listdir(self.folder):
            p = os.path.join(self.folder, f)
            if f == self.part and os.path.isdir(p):
                shutil.rmtree(p, ignore_errors=True)
            elif f.startswith(self.part + '.') and '.tmp.' not in f and os.path.isfile(p):
                try:
                    os.remove(p)
                except FileNotFoundError:
                    pass


class BuildContext:
    """`ctx` for one part call.

    ctx.part      part name
    ctx.stage     stages.StageInfo in build_stage (id, archive, family, layout, direction, level,
                  track_name, height, world_offset, vpath(rel), cache_dir, to_json()); None otherwise
    ctx.vfs       vfs.Vfs: engine virtual file system (find/read/read_text/listdir/files_under/real_path,
                  texture_candidates/resolve_texture); reads straight from the archives
    ctx.archives  archive.ArchiveSet (raw archive access)
    ctx.full      root of the extracted cache (same layout as research/full) for the copied parsers in
                  lib/formats (they read it through their FULL constant)
    ctx.textures  texture registry (textures.BoundTextures): use(name[, stage]) -> texId, cube(name[, stage])
                  -> [6 texIds], use_file(archive, member), resolve(), info(texId), alpha_class(texId)
    ctx.out       Output for this part's slot (stage folder, global folder); None in build_cars
    ctx.car_out(name) -> Output for cars/<name>/ (build_cars)
    ctx.out_root  output root (public/assets)
    ctx.log(msg) / ctx.warn(msg)
    """

    def __init__(self, part, out_root, vfs, registry, full, stage=None, out=None, log=print):
        self.part = part
        self.out_root = out_root
        self.vfs = vfs
        self.archives = vfs.archives
        self.full = full
        self.stage = stage
        self.out = out
        self.textures = T.BoundTextures(registry, stage)
        self.warnings = []
        self._log = log

    def car_out(self, car_name):
        return Output(os.path.join(self.out_root, 'cars', car_name), self.part)

    def log(self, msg):
        tag = self.stage.id if self.stage else '-'
        self._log('[%s %s] %s' % (self.part, tag, msg))

    def warn(self, msg):
        self.warnings.append(msg)
        self.log('WARNING ' + msg)
