"""Stage ids <-> archives <-> level paths, and per-stage facts every part needs.

  stage id (rally-web, src/world/ports)   corsica-1-f      hillclimb-1a-f
  archive (original_version .rff)         corsica1f        hillclimb1af
  level path (engine virtual path)        track/corsica1/forward      track/hillclimb1a/forward

Order and ids are PORTED_ORDER in src/world/ports/index.ts (generated by research/tools/port_tracks.py),
read from that file so the pipeline never drifts from the game's catalogue.

`Start.con` holds `Game.createTrack <Name> <Forward|Reverse> <H>`: H is the world y offset. Objects.con,
the MergeMesh/MergeObjects .dat files and Start.con's own positions are in the original WORLD frame:
    sim = world - (2048, H, 2048)          (research/formats/objects.md §1.3)
Meshes (.qm, .gcm) and AiFiles/*.spl are already in the SIM frame (original left-handed, = rally-web sim
space); three space is sim with z negated (docs/ARCHITECTURE.md §2).
"""
import os
import re
from dataclasses import dataclass

import archive as A

FAMILIES = ('corsica', 'hillclimb', 'iceracing', 'kenya', 'newzealand', 'rallycross')
WORLD_XZ_OFFSET = 2048.0
_ID_RE = re.compile(r'^(%s)-(\d[abc]?)-([fr])$' % '|'.join(FAMILIES))
_ARCH_RE = re.compile(r'^(%s)(\d[abc]?)([fr])$' % '|'.join(FAMILIES))
PORTS_INDEX = os.path.join(A.REPO, 'src', 'world', 'ports', 'index.ts')


def stage_archive(stage_id):
    """'corsica-1-f' -> 'corsica1f' (None for anything that is not a ported stage id)."""
    m = _ID_RE.match(stage_id)
    return '%s%s%s' % m.groups() if m else None


def archive_stage_id(arch):
    """'hillclimb1af' -> 'hillclimb-1a-f' (None for non-track archives such as Misc, common, fogzor)."""
    m = _ARCH_RE.match(arch)
    return '%s-%s-%s' % m.groups() if m else None


def level_path(stage_id):
    """'hillclimb-1a-f' -> 'track/hillclimb1a/forward' (lower case virtual path)."""
    m = _ID_RE.match(stage_id)
    if not m:
        return None
    fam, num, d = m.groups()
    return 'track/%s%s/%s' % (fam, num, 'forward' if d == 'f' else 'reverse')


def ported_order():
    """The 48 stage ids in catalogue order (PORTED_ORDER in src/world/ports/index.ts); falls back to the
    track archives found in original_version when the TS file is unavailable."""
    try:
        with open(PORTS_INDEX, encoding='utf-8') as f:
            m = re.search(r'PORTED_ORDER[^=]*=\s*Object\.freeze\(\[([^\]]*)\]', f.read())
        if m:
            ids = re.findall(r"'([^']+)'", m.group(1))
            if ids:
                return ids
    except OSError:
        pass
    ids = [archive_stage_id(n) for n in A.archive_paths()]
    return [i for i in ids if i]


@dataclass(frozen=True)
class StageInfo:
    id: str              # 'corsica-1-f'
    archive: str         # 'corsica1f'
    family: str          # 'corsica'
    layout: str          # 'corsica1'   (track folder name; forward and reverse share it)
    direction: str       # 'forward' | 'reverse'
    level: str           # 'track/corsica1/forward'   (virtual level folder, lower case)
    track_name: str      # 'Corsica1'   (Game.createTrack's first argument)
    height: float        # H: Game.createTrack's third argument (world y offset)

    @property
    def reverse(self):
        return self.direction == 'reverse'

    @property
    def world_offset(self):
        """(2048, H, 2048): sim = world - world_offset for Objects.con / MergeObjects / Start.con."""
        return (WORLD_XZ_OFFSET, self.height, WORLD_XZ_OFFSET)

    def vpath(self, rel):
        """Virtual path of a file in the level folder: vpath('Mesh/Track.qm') -> 'track/corsica1/forward/mesh/track.qm'."""
        return '%s/%s' % (self.level, rel.replace('\\', '/').lower().lstrip('/'))

    @property
    def cache_dir(self):
        """The level folder in the extracted cache (research/full layout):
        .cache/original/<archive>/track/<layout>/<direction>  (exists once the archive is extracted)."""
        return os.path.join(A.FULL, self.archive, *self.level.split('/'))

    def to_json(self):
        return {'id': self.id, 'archive': self.archive, 'family': self.family, 'layout': self.layout,
                'direction': self.direction, 'level': self.level, 'trackName': self.track_name,
                'height': self.height, 'worldOffset': list(self.world_offset)}


def parse_start_con(text):
    """-> (track name, 'Forward'|'Reverse', H) from `Game.createTrack <Name> <Dir> <H>` (case-insensitive)."""
    for raw in text.splitlines():
        t = raw.split()
        if len(t) >= 4 and t[0].lower() == 'game.createtrack':
            return t[1], t[2], float(t[3])
    raise ValueError('Start.con has no Game.createTrack line')


def load_stage(stage_id, vfs):
    """StageInfo for a ported stage id, reading Start.con from its archive (memoised per Vfs)."""
    cache = vfs.__dict__.setdefault('_stage_info', {})
    if stage_id not in cache:
        cache[stage_id] = _load_stage(stage_id, vfs)
    return cache[stage_id]


def _load_stage(stage_id, vfs):
    arch = stage_archive(stage_id)
    if arch is None:
        raise KeyError('not a ported stage id: %r' % stage_id)
    lvl = level_path(stage_id)
    _, layout, direction = lvl.split('/')
    fam = _ID_RE.match(stage_id).group(1)
    name, d, h = parse_start_con(vfs.read_text(lvl + '/start.con', prefer=arch))
    if d.lower() != direction:
        raise ValueError('%s: Start.con direction %s != %s' % (stage_id, d, direction))
    return StageInfo(id=stage_id, archive=arch, family=fam, layout=layout, direction=direction, level=lvl,
                     track_name=name, height=h)


def as_stage(stage, vfs):
    """Accept a StageInfo, a stage id or an archive name."""
    if stage is None or isinstance(stage, StageInfo):
        return stage
    if isinstance(stage, str):
        sid = stage if _ID_RE.match(stage) else archive_stage_id(stage)
        if sid:
            return load_stage(sid, vfs)
    raise KeyError('unknown stage %r' % (stage,))
