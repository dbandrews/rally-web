/**
 * src/core/assets.ts — runtime access to the converted ORIGINAL assets (public/assets/, built by
 * `npm run assets`; pipeline and formats: docs/ASSETS.md). Shared by render / world / audio: no three.js here.
 *
 * Everything is optional. When public/assets/ is absent (CI, tests, a fresh clone), when the manifest is
 * unreadable or of another version, or when the page has `?orig=0`, getAssetManifest() resolves to null and
 * every consumer keeps today's procedural visuals / world / synth audio. No errors are thrown for that case;
 * callers that fetch part files should catch, call warnOnce() and fall back.
 *
 * Layout (relative to assetBaseUrl()):
 *   manifest.json                          AssetManifest (regenerated by every build run)
 *   stages/<stage id>/<part>.json (+ .bin…) per-stage parts (track, collision, objects, environment, …)
 *   cars/<CarName>/<part>.json (+ …)        per-car parts
 *   global/<part>.json (+ …)                shared parts (audio bank, …)
 *   tex/<texId>.rtex                        textures (src/render/orig/rtex.ts)
 *
 * Stage ids: `corsica-1-f` ↔ archive `corsica1f` ↔ level path `track/corsica1/forward`;
 * `hillclimb-1a-f` ↔ `hillclimb1af` ↔ `track/hillclimb1a/forward` (PORTED_ORDER, src/world/ports).
 */

/** Must equal tools/assets/lib/manifest.py MANIFEST_VERSION. */
export const ASSET_MANIFEST_VERSION = 1;

export interface AssetManifest {
  version: number;
  /** stage id → parts present (a part is listed iff stages/<id>/<part>.json exists). */
  stages: Record<string, string[]>;
  /** Car folder names (original spelling, e.g. "AudiS1") with at least one part. */
  cars: string[];
  /** Car name → parts present. */
  carParts: Record<string, string[]>;
  /** Global parts present (global/<part>.json). */
  global: string[];
  /** The original sound bank is present (global/audio.json). */
  audio: boolean;
  /** Number of tex/*.rtex files. */
  textures: number;
}

// ------------------------------------------------------------------------------------------- URL flags

/** Value of a URL query parameter (null outside the browser or when absent). */
export function urlParam(name: string): string | null {
  try {
    return typeof window !== 'undefined' && window.location ? new URLSearchParams(window.location.search).get(name) : null;
  } catch {
    return null;
  }
}

const isOff = (v: string | null) => v !== null && /^(0|false|no|off)$/i.test(v);

/** `?orig=0` disables every original asset (procedural fallback everywhere). */
export function origAssetsDisabled(): boolean {
  return isOff(urlParam('orig'));
}

// ------------------------------------------------------------------------------------------- URLs

/** Base URL of the asset packs: Vite's BASE_URL (`./` in builds, `/` in dev) + `assets/`. */
export function assetBaseUrl(): string {
  let base = '/';
  try {
    base = import.meta.env?.BASE_URL ?? '/';
  } catch {
    /* non-Vite runtime */
  }
  return (base.endsWith('/') ? base : base + '/') + 'assets/';
}

/** Absolute-or-relative URL of a file under public/assets/ (`rel` like `stages/corsica-1-f/track.json`). */
export function assetUrl(rel: string): string {
  return assetBaseUrl() + rel.replace(/^\/+/, '');
}

export const stagePartPath = (stageId: string, part: string, ext = 'json') => `stages/${stageId}/${part}.${ext}`;
export const carPartPath = (car: string, part: string, ext = 'json') => `cars/${car}/${part}.${ext}`;
export const globalPartPath = (part: string, ext = 'json') => `global/${part}.${ext}`;
export const texturePath = (texId: string) => `tex/${texId}.rtex`;

// ------------------------------------------------------------------------------------------- fetching

type FetchFn = (url: string, init?: RequestInit) => Promise<Response>;
let fetchOverride: FetchFn | null = null;

function fetchFn(): FetchFn | null {
  if (fetchOverride) return fetchOverride;
  if (typeof window === 'undefined' || typeof fetch !== 'function') return null; // node / vitest: no assets
  return (u, i) => fetch(u, i);
}

/** GET a file under public/assets/ as JSON. Throws on network / HTTP / parse errors. */
export async function fetchJson<T = unknown>(rel: string, init?: RequestInit): Promise<T> {
  const f = fetchFn();
  if (!f) throw new Error('assets: fetch unavailable');
  const r = await f(assetUrl(rel), init);
  if (!r.ok) throw new Error(`assets: ${rel}: HTTP ${r.status}`);
  return (await r.json()) as T;
}

/** GET a file under public/assets/ as bytes. Throws on network / HTTP errors. */
export async function fetchArrayBuffer(rel: string, init?: RequestInit): Promise<ArrayBuffer> {
  const f = fetchFn();
  if (!f) throw new Error('assets: fetch unavailable');
  const r = await f(assetUrl(rel), init);
  if (!r.ok) throw new Error(`assets: ${rel}: HTTP ${r.status}`);
  return r.arrayBuffer();
}

// ------------------------------------------------------------------------------------------- manifest

/** Validate a manifest JSON value; null for anything that is not a version-matching manifest. */
export function parseManifest(v: unknown): AssetManifest | null {
  if (!v || typeof v !== 'object') return null;
  const o = v as Record<string, unknown>;
  if (o.version !== ASSET_MANIFEST_VERSION) {
    if (typeof o.version === 'number') warnOnce('manifest-version', `[assets] manifest version ${o.version} != ${ASSET_MANIFEST_VERSION}: run npm run assets (using procedural visuals)`);
    return null;
  }
  const strList = (x: unknown): string[] => (Array.isArray(x) ? x.filter((s): s is string => typeof s === 'string') : []);
  const listMap = (x: unknown): Record<string, string[]> => {
    const out: Record<string, string[]> = {};
    if (x && typeof x === 'object') for (const [k, val] of Object.entries(x)) out[k] = strList(val);
    return out;
  };
  return {
    version: ASSET_MANIFEST_VERSION,
    stages: listMap(o.stages),
    cars: strList(o.cars),
    carParts: listMap(o.carParts),
    global: strList(o.global),
    audio: o.audio === true,
    textures: typeof o.textures === 'number' ? o.textures : 0,
  };
}

let manifestPromise: Promise<AssetManifest | null> | null = null;

/**
 * The asset manifest, fetched once and cached (also the null result). null when the assets are absent,
 * unreadable or of another version, outside the browser, or with `?orig=0`. Never rejects.
 */
export function getAssetManifest(): Promise<AssetManifest | null> {
  if (!manifestPromise) {
    manifestPromise = (async () => {
      if (origAssetsDisabled() || !fetchFn()) return null;
      try {
        // the dev server answers `null` when public/assets/manifest.json is missing (vite.config.ts), so a
        // fresh clone logs no 404; a static build without assets ships the same `null` file
        return parseManifest(await fetchJson<unknown>('manifest.json', { cache: 'no-cache' }));
      } catch (e) {
        warnOnce('manifest', `[assets] no original asset manifest (${(e as Error).message}): using procedural visuals`);
        return null;
      }
    })();
  }
  return manifestPromise;
}

/** Parts listed for a stage (empty when none / no manifest). */
export function manifestStageParts(m: AssetManifest | null, stageId: string): readonly string[] {
  return (m && m.stages[stageId]) || [];
}

export function manifestHasStagePart(m: AssetManifest | null, stageId: string, part: string): boolean {
  return manifestStageParts(m, stageId).includes(part);
}

/** True when the manifest lists `part` for `stageId` (false without a manifest). */
export async function hasStagePart(stageId: string, part: string): Promise<boolean> {
  return manifestHasStagePart(await getAssetManifest(), stageId, part);
}

// ------------------------------------------------------------------------------------------- stage ids

const FAMILIES = ['corsica', 'hillclimb', 'iceracing', 'kenya', 'newzealand', 'rallycross'] as const;
export type OrigFamily = (typeof FAMILIES)[number];
const ID_RE = new RegExp(`^(${FAMILIES.join('|')})-(\\d[abc]?)-([fr])$`);
const ARCH_RE = new RegExp(`^(${FAMILIES.join('|')})(\\d[abc]?)([fr])$`);

/** True for the 48 ported stage ids (`corsica-1-f` … `rallycross-3-r`), by pattern. */
export function isPortedStageId(id: string): boolean {
  return ID_RE.test(id);
}

/** `corsica-1-f` → `corsica1f`, `hillclimb-1a-f` → `hillclimb1af`; null for non-ported ids. */
export function stageArchive(id: string): string | null {
  const m = ID_RE.exec(id);
  return m ? `${m[1]}${m[2]}${m[3]}` : null;
}

/** `hillclimb1af` → `hillclimb-1a-f`; null for other archive names (Misc, common, fogzor, …). */
export function archiveStageId(archive: string): string | null {
  const m = ARCH_RE.exec(archive);
  return m ? `${m[1]}-${m[2]}-${m[3]}` : null;
}

/** `hillclimb-1a-f` → `track/hillclimb1a/forward` (the engine's level folder, lower case). */
export function stageLevelPath(id: string): string | null {
  const m = ID_RE.exec(id);
  return m ? `track/${m[1]}${m[2]}/${m[3] === 'f' ? 'forward' : 'reverse'}` : null;
}

export function stageFamily(id: string): OrigFamily | null {
  const m = ID_RE.exec(id);
  return m ? (m[1] as OrigFamily) : null;
}

// ------------------------------------------------------------------------------------------- diagnostics

const warned = new Set<string>();

/** console.warn once per key (asset failures log one warning, then the caller falls back). */
export function warnOnce(key: string, msg: string): void {
  if (warned.has(key)) return;
  warned.add(key);
  console.warn(msg);
}

// ------------------------------------------------------------------------------------------- tests

/** Tests only: replace fetch (null restores) and forget the cached manifest. */
export function _setAssetFetchForTests(f: FetchFn | null): void {
  fetchOverride = f;
  manifestPromise = null;
  warned.clear();
}
