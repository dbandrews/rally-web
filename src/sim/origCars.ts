/**
 * src/sim/origCars.ts — car data of EVERY original car (29), OWNED BY THE CARS BUILDER (asset-port phase).
 *
 * Per-car handling facts from the original's per-car PhysicsCar.con configs (research/car_survey.md): mass, torque
 * scale, drive type, gear ratios (index 0 = reverse), turbo size; plus the car's own geometry the sim needs so the
 * real body sits on its real wheels: the wheel bundle positions of Templates.con (CarWheel setPosition, SIM body
 * frame; FR / RR mirror x exactly on every car, research/formats/cars.md §4.4) and the hull box of
 * Misc/object/Car_<Name>.col (the first 8 of the car_NColPoints = 12 points form a box: front / rear z, bottom y).
 * Everything else in the survey (wheel physics, inertia, spring lengths 0.75, wheel radius 0.30, …) is identical on
 * all 29 cars and already in ARCHETYPE_PARAMS (docs/MECHANICS_SPEC.md §3).
 *
 * `archive` is the original car's folder name = ORIG_CAR_IDS (src/core/constants.ts) = RaceSelection.car =
 * the asset manifest's `cars` key. The game shows the real cars under their real names (AGENTS.md: a full faithful
 * port; the display names come from LocaleEnglish via the built assets, tools/assets/parts/cars.py) — the old
 * "neutral labels" rule of the mechanics-only phase no longer applies.
 *
 * REQUIRED EXPORTS: ORIG_CARS: readonly OrigCar[] (presets.ts builds one TuningPreset per car), origCarById(name).
 */
import type { V3 } from '../core/types';

export interface OrigCar {
  /** Original car folder name (= ORIG_CAR_IDS entry, RaceSelection.car). */
  readonly archive: string;
  /** 0 = FWD, 1 = RWD, 2 = AWD. */
  readonly drive: 0 | 1 | 2;
  readonly mass: number;
  readonly torqueScale: number;
  readonly turboSize: 0 | 1;
  /** Gears per index 0 = reverse, 1..n forward. */
  readonly gearRatio: readonly number[];
  /** Front-left / rear-left wheel bundle position (Templates.con), SIM body frame; FR / RR mirror x. */
  readonly wheelFL: Readonly<V3>;
  readonly wheelRL: Readonly<V3>;
  /** Hull box of Car_<Name>.col: front / rear z, bottom y (SIM body frame, m). */
  readonly hullFrontZ: number;
  readonly hullRearZ: number;
  readonly hullBottomY: number;
  /** Championship/event ids the car is entered in (research/extracted/Misc/aitimes). */
  readonly events: readonly string[];
}

